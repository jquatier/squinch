// Subsets the bundled Inter weights to the metrics repertoire and emits
// src/fonts.generated.ts (base64 woff2), so every rendered SVG can embed the
// exact face the metrics tables were measured from. Text then renders
// identically everywhere — including GitHub's <img> sandbox — instead of
// falling back to whatever the viewer has installed.
//
// Run: npm run gen-fonts   (build-time only; output is committed)
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import subsetFont from "subset-font";

const require = createRequire(import.meta.url);
const metrics = JSON.parse(readFileSync("metrics.json", "utf8"));

const out: Record<string, string> = {};
for (const weight of Object.keys(metrics)) {
  const file = require.resolve(
    `@fontsource/inter/files/inter-latin-${weight}-normal.woff2`,
  );
  const repertoire = Object.keys(metrics[weight].advances).join("");
  const woff2 = await subsetFont(readFileSync(file), repertoire, {
    targetFormat: "woff2",
  });
  out[weight] = woff2.toString("base64");
  console.log(`subset ${weight}: ${woff2.length} bytes (${repertoire.length} chars)`);
}

writeFileSync(
  "src/fonts.generated.ts",
  `// GENERATED by scripts/gen-fonts.ts — do not edit.\n` +
    `// Inter subset to the metrics repertoire, woff2, base64. Embedded in every\n` +
    `// rendered SVG via @font-face so text matches the precomputed metrics\n` +
    `// everywhere (non-negotiable: rendering never depends on installed fonts).\n` +
    `export const FONTS: Record<"400" | "500", string> = ${JSON.stringify(out)};\n`,
);
console.log("wrote src/fonts.generated.ts");
